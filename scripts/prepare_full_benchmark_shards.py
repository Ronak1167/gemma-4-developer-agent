import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
manifest = ROOT / "starter" / "official" / "tasks.jsonl"
shard_manifest = ROOT / "reports" / "benchmark-shards.json"
tasks = [json.loads(x) for x in manifest.read_text(encoding="utf-8").splitlines() if x.strip()]
plan = json.loads(shard_manifest.read_text(encoding="utf-8"))
assert len(tasks) == 129 and plan["task_count"] == 129 and plan["shard_count"] == 4
task_map = {x["instance_id"]: x for x in tasks}
base_path = ROOT / "experiments" / "kaggle_mini_benchmark.ipynb"
base = json.loads(base_path.read_text(encoding="utf-8"))
base_code = "\n".join("".join(c.get("source", [])) for c in base["cells"] if c["cell_type"] == "code")
assert "AUTHORIZE_GPU_SMOKE_TEST = False" in base_code
assert "AUTHORIZE_GPU_SMOKE_TEST = True" not in base_code
assert "ronak1167/gemma4-optimized-candidate" in base_code
assert "compaction_interval=15" in base_code and "token_threshold=14336" in base_code

metadata_template = {
    "language": "python",
    "kernel_type": "notebook",
    "is_private": True,
    "enable_gpu": True,
    "enable_tpu": False,
    "machine_shape": "NvidiaL4",
    "docker_image": "gcr.io/kaggle-private-byod/python@sha256:37c64f7dd9c54116ecd1bcc88817c5469b88387388fade02bfa8bf3fc647d461",
    "enable_internet": False,
    "dataset_sources": [
        "metric/gemma-4-developer-agent-wheelhouse",
        "ronak1167/gemma4-optimized-candidate",
    ],
    "competition_sources": ["gemma-4-developer-agent"],
    "kernel_sources": [],
    "model_sources": ["google/gemma-4/Other/gemma-4-12b-it-qat-w4a16-ct/2"],
}

all_ids = []
for shard in plan["shards"]:
    index = shard["shard"]
    ids = shard["task_ids"]
    assert len(ids) == shard["task_count"]
    assert all(tid in task_map for tid in ids)
    all_ids.extend(ids)
    expected = {tid: task_map[tid]["repo"] for tid in ids}
    folder = DIST / f"kaggle_full_shard_{index}"
    folder.mkdir(parents=True, exist_ok=True)
    nb = json.loads(json.dumps(base))
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        src = "".join(cell.get("source", []))
        if "TARGET_TASK_IDS =" in src and "EXPECTED_REPOS =" in src:
            src, n = re.subn(
                r'TARGET_TASK_IDS = \[[^\]]*\]',
                "TARGET_TASK_IDS = " + repr(ids),
                src, count=1
            )
            assert n == 1
            repo_literal = "EXPECTED_REPOS = " + repr(expected)
            src, n = re.subn(
                r'EXPECTED_REPOS = \{.*?\n\}',
                repo_literal,
                src, count=1, flags=re.S
            )
            assert n == 1
        src = src.replace(
            'Path("/kaggle/working/results/mini_benchmark")',
            f'Path("/kaggle/working/results/full_benchmark/shard_{index}")'
        )
        src = src.replace(
            '"FOUR_TASK_MULTI_REPOSITORY_MINI_BENCHMARK"',
            f'"FULL_BENCHMARK_SHARD_{index}"'
        )
        src = src.replace(
            'Path("/kaggle/working/mini_benchmark_diagnostic.json")',
            f'Path("/kaggle/working/full_benchmark_shard_{index}_diagnostic.json")'
        )
        src = src.replace(
            '"No leaderboard parquet file generated by this diagnostic notebook."' ,
            '"Per-shard predictions are exported separately; no competition submission is made."'
        )
        src = src.replace(
            '"Diagnostic only. Evaluator outputs are in results/mini_benchmark/. No leaderboard artifact is generated."',
            '"Diagnostic only. Evaluator outputs are in the shard results directory. Per-shard predictions are exported separately; no competition submission is made."'
        )
        export_block = f'''print("[CONFIRMED] No pre-existing parquet artifacts before shard export.")
import pandas as pd
submission_rows = []
for tid in TARGET_TASK_IDS:
    patch_path = RESULTS_DIR / "patches" / f"{{tid}}.patch"
    prediction = patch_path.read_text(encoding="utf-8") if patch_path.is_file() and patch_path.stat().st_size else "NO_PATCH"
    submission_rows.append({{"id": tid, "prediction": prediction}})
shard_submission = pd.DataFrame(submission_rows, columns=["id", "prediction"])
assert len(shard_submission) == len(TARGET_TASK_IDS)
assert set(shard_submission["id"]) == set(TARGET_TASK_IDS)
submission_path = Path("/kaggle/working/submission_shard_{index}.parquet")
shard_submission.to_parquet(submission_path, index=False)
assert submission_path.is_file() and submission_path.stat().st_size > 0
print(f"[SHARD EXPORT] {{submission_path}}: {{len(shard_submission)}} rows")
'''
        src = src.replace(
            'print("[CONFIRMED] No leaderboard submission parquet file generated.")',
            export_block.rstrip()
        )
        cell["source"] = src.splitlines(keepends=True)
    nb_text = "\n".join("".join(c.get("source", [])) for c in nb["cells"] if c["cell_type"] == "code")
    assert "AUTHORIZE_GPU_SMOKE_TEST = False" in nb_text
    assert "AUTHORIZE_GPU_SMOKE_TEST = True" not in nb_text
    assert f'full_benchmark/shard_{index}' in nb_text
    assert f'FULL_BENCHMARK_SHARD_{index}' in nb_text
    assert "Path(\"/kaggle/working/results/mini_benchmark\")" not in nb_text
    assert "submission_shard_" in nb_text and "to_parquet(submission_path" in nb_text
    notebook_name = f"kaggle_full_shard_{index}.ipynb"
    (folder / notebook_name).write_text(
        json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8"
    )
    slug = f"ronak1167/gemma-4-swe-agent-full-benchmark-shard-{index + 1}"
    metadata = dict(metadata_template)
    metadata.update({
        "id": slug,
        "title": f"Gemma 4 SWE Agent Full Benchmark Shard {index + 1}",
        "code_file": notebook_name,
    })
    (folder / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8"
    )
    print(
        f"SHARD {index + 1}: {len(ids)} tasks | {slug} | gate CLOSED | "
        f"15-minute per-task budget | output=shard_{index}"
    )

assert len(all_ids) == 129 and len(set(all_ids)) == 129
assert set(all_ids) == set(task_map)
print("[PASS] Four full-benchmark shard notebooks generated.")
print("[PASS] All 129 official task IDs appear exactly once.")
print("[PASS] All four GPU execution gates are closed.")
